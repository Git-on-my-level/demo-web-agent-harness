export const worldSeed = {
  html: worldSeedHtml.trim(),
  cssHref: "styles/world-seed.css",
  sparkleLayerId: "sparkle-layer",
  sparkleCount: 30
};

export function seedSparkles(agentWorldElement = document.getElementById("agent-world")) {
  const layer = agentWorldElement?.querySelector?.("#sparkle-layer");
  if (!layer) {
    return 0;
  }

  for (let i = 0; i < worldSeed.sparkleCount; i += 1) {
    const sparkle = document.createElement("div");
    sparkle.className = "sparkle";
    sparkle.style.left = (Math.random() * 100) + "%";
    sparkle.style.top = (Math.random() * 100) + "%";
    sparkle.style.animationDelay = (Math.random() * 3) + "s";
    sparkle.style.animationDuration = (2 + Math.random() * 3) + "s";
    sparkle.style.width = (2 + Math.random() * 4) + "px";
    sparkle.style.height = sparkle.style.width;
    layer.appendChild(sparkle);
  }

  return worldSeed.sparkleCount;
}

export function initializeWorldSeed(agentWorldElement = document.getElementById("agent-world")) {
  return {
    sparkleCount: seedSparkles(agentWorldElement)
  };
}
